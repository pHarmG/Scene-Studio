class InstallerUiHandler(BaseHTTPRequestHandler):
    server_version = "SceneStudioInstallerUI/1.0"
    session: InstallerSession  # injected via server attribute

    # -- plumbing -------------------------------------------------------------

    def log_message(self, fmt, *args):  # keep the operator console quiet
        return

    def _json(self, status: int, payload) -> None:
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _error(self, status: int, message: str) -> None:
        self._json(status, {"error": message})

    def _read_json_body(self) -> dict:
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0:
            return {}
        if length > MAX_BODY_BYTES:
            raise UiError(413, "request body too large")
        raw = self.rfile.read(length)
        try:
            payload = json.loads(raw.decode("utf-8"))
        except (json.JSONDecodeError, UnicodeDecodeError):
            raise UiError(400, "request body is not valid JSON") from None
        if not isinstance(payload, dict):
            raise UiError(400, "request body must be a JSON object")
        return payload

    def _guard(self) -> None:
        """Loopback, Host-header, and session-token checks for /api calls."""
        port = self.server.server_address[1]
        allowed_hosts = {f"127.0.0.1:{port}", f"localhost:{port}", f"[::1]:{port}"}
        if self.headers.get("Host", "") not in allowed_hosts:
            raise UiError(403, "unexpected Host header")
        if self.headers.get("X-Scene-Studio-Token") != self.session.token:
            raise UiError(401, "missing or wrong session token (open the URL printed by the server)")

    def _dispatch(self, method: str) -> None:
        path = self.path.split("?", 1)[0]
        try:
            if path.startswith("/api/"):
                self._guard()
                handler = getattr(self, f"api_{method.lower()}_{path[len('/api/'):].replace('/', '_')}", None)
                if handler is None:
                    raise UiError(404, f"unknown API route: {method} {path}")
                handler()
                return
            if method == "GET":
                self._serve_static(path)
                return
            raise UiError(405, "method not allowed")
        except UiError as exc:
            try:
                self._error(exc.status, exc.message)
            except (BrokenPipeError, ConnectionResetError):
                pass
        except (BrokenPipeError, ConnectionResetError):
            pass

    def do_GET(self):  # noqa: N802
        self._dispatch("GET")

    def do_POST(self):  # noqa: N802
        self._dispatch("POST")

    # -- static ---------------------------------------------------------------

    STATIC_FILES = {
        "/": ("index.html", "text/html; charset=utf-8"),
        "/index.html": ("index.html", "text/html; charset=utf-8"),
        "/app.js": ("app.js", "text/javascript; charset=utf-8"),
        "/style.css": ("style.css", "text/css; charset=utf-8"),
    }

    def _serve_static(self, path: str) -> None:
        entry = self.STATIC_FILES.get(path)
        if entry is None:
            self._error(404, "not found")
            return
        filename, content_type = entry
        try:
            body = (STATIC_DIR / filename).read_bytes()
        except OSError:
            self._error(500, f"static file missing: {filename} — the installer UI is incomplete.")
            return
        self.send_response(200)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header(
            "Content-Security-Policy",
            "default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'",
        )
        self.end_headers()
        self.wfile.write(body)

    # -- API -------------------------------------------------------------------

    def api_get_session(self) -> None:
        self._json(200, self.session.public_session())

    def api_post_answers(self) -> None:
        if self.session.run_status == "running":
            raise UiError(409, "An install is running; answers are locked until it finishes.")
        patch = self._read_json_body()
        self._json(200, {"answers": self.session.update_answers(patch)})

    def api_post_secrets(self) -> None:
        body = self._read_json_body()
        changed = {}
        for name in ("ha_token", "hue_key"):
            if name in body:
                self.session.set_secret(name, body[name])
                changed[name] = True
        with self.session.lock:
            env_ha = bool(os.environ.get("SCENE_STUDIO_HA_TOKEN"))
            self._json(
                200,
                {"secrets_entered": {"ha_token": bool(self.session.ha_token or env_ha), "hue_key": bool(self.session.hue_key)}},
            )

    def api_post_probe(self) -> None:
        body = self._read_json_body()
        names = body.get("names")
        if not isinstance(names, list) or not names or not all(isinstance(item, str) for item in names):
            raise UiError(400, "expected body {\"names\": [probe, ...]}")
        results = self.session.run_probes(names)
        # probes may refine the answers (e.g. a detected config root is
        # auto-selected); echo them back so the UI stays in sync
        with self.session.lock:
            self._json(200, {"results": results, "answers": self.session.public_answers()})

    def api_post_hue_pair(self) -> None:
        body = self._read_json_body()
        self._json(200, self.session.pair_hue(str(body.get("host") or "")))

    def api_post_plan(self) -> None:
        self._json(200, self.session.build_plan())

    def api_post_apply(self) -> None:
        body = self._read_json_body()
        self._json(200, self.session.start_apply(str(body.get("confirm") or "")))

    def api_get_run(self) -> None:
        query = self.path.split("?", 1)[1] if "?" in self.path else ""
        since = 0
        for part in query.split("&"):
            if part.startswith("since="):
                try:
                    since = int(part[6:])
                except ValueError:
                    since = 0
        self._json(200, self.session.run_snapshot(since))

    def api_post_reset(self) -> None:
        self._json(200, self.session.reset())


class InstallerUiServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, address, handler_class, session: InstallerSession):
        super().__init__(address, handler_class)
        self.session = session


