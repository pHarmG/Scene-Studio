class UiError(Exception):
    """A request-level failure with a user-facing message."""

    def __init__(self, status: int, message: str):
        self.status = status
        self.message = message
        super().__init__(message)


# ---------------------------------------------------------------------------
# small cross-platform process helpers
# ---------------------------------------------------------------------------


def find_tool(name: str) -> str | None:
    return shutil.which(name)


def run_command(argv, *, timeout: float | None = None, input_text: str | None = None, env: dict | None = None):
    """subprocess.run with the one Windows quirk handled: .cmd shims must go
    through cmd.exe when CreateProcess cannot execute them directly."""
    argv = [str(part) for part in argv]
    if sys.platform == "win32" and argv[0].lower().endswith((".cmd", ".bat")):
        argv = ["cmd.exe", "/c", *argv]
    return subprocess.run(
        argv,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=timeout,
        input=input_text,
        env=env,
    )


def bash_single_quote(value: str) -> str:
    """Escape for embedding inside single quotes in a remote shell command
    (same convention as the PowerShell installers)."""
    return value.replace("'", "'\"'\"'")


def tcp_reachable(host: str, port: int, timeout: float = 4.0) -> bool:
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def insecure_ssl_context() -> ssl.SSLContext:
    context = ssl.create_default_context()
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    return context


def http_probe(url: str, *, headers: dict | None = None, timeout: float = 8.0) -> dict:
    """GET a URL; any HTTP answer (even 401) proves reachability.

    Returns {"ok": bool, "http_status": int|None, "body": dict|None,
    "error": str|None} — connection failures carry ``error``.
    """
    request = urllib.request.Request(url, headers=headers or {})
    try:
        with urllib.request.urlopen(  # noqa: S310 - installer probing user-specified LAN endpoints
            request, timeout=timeout, context=insecure_ssl_context()
        ) as response:
            raw = response.read(65536)
            status = response.status
    except urllib.error.HTTPError as exc:
        return {"ok": True, "http_status": exc.code, "body": None, "error": None}
    except (urllib.error.URLError, OSError, ValueError) as exc:
        return {"ok": False, "http_status": None, "body": None, "error": str(exc)}
    body = None
    try:
        body = json.loads(raw.decode("utf-8", errors="replace"))
    except (json.JSONDecodeError, UnicodeDecodeError):
        pass
    return {"ok": True, "http_status": status, "body": body, "error": None}


# ---------------------------------------------------------------------------
# apps.yaml merge preview — a faithful port of the wizard's deterministic
# text merge (Merge-SceneStudioBlock). PREVIEW ONLY: the wizard performs the
# real write with its own copy of this logic.
# ---------------------------------------------------------------------------


def find_block_range(lines: list[str]) -> tuple[int, int] | None:
    for i, line in enumerate(lines):
        if line == BLOCK_START_MARKER:
            for j in range(i + 1, len(lines)):
                if lines[j] == BLOCK_END_MARKER:
                    return (i, j)
            raise UiError(
                400,
                "apps.yaml contains an unterminated scene_studio managed block; fix it manually on the target.",
            )
    for i, line in enumerate(lines):
        if re.match(r"^scene_studio:\s*$", line):
            end = len(lines) - 1
            for j in range(i + 1, len(lines)):
                if re.match(r"^[A-Za-z0-9_-]+:", lines[j]) or lines[j] == BLOCK_START_MARKER:
                    end = j - 1
                    break
            return (i, end)
    return None


def merge_block_preview(original_text: str, block_text: str) -> str:
    managed = [BLOCK_START_MARKER, *block_text.split("\n"), BLOCK_END_MARKER]
    if not original_text.strip():
        return "\n".join(managed) + "\n"
    lines = original_text.replace("\r\n", "\n").split("\n")
    trailing_newline = bool(lines) and lines[-1] == ""
    if trailing_newline:
        lines = lines[:-1]
    rng = find_block_range(lines)
    if rng is not None:
        before = lines[: rng[0]]
        after = lines[rng[1] + 1 :]
    else:
        before = list(lines)
        while before and before[-1] == "":
            before.pop()
        before = [*before, ""]
        after = []
    text = "\n".join([*before, *managed, *after])
    if trailing_newline or not text.endswith("\n"):
        text += "\n"
    return text


