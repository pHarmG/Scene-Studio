#!/usr/bin/env python3
"""Scene Studio installer UI — a local, browser-based guided installer.

A small stdlib-only web server that serves the static wizard SPA
(``installer/ui/static``) and drives the EXISTING guided installer. It adds
no install logic of its own:

* every question the CLI wizard asks becomes a form field, and every probe
  the wizard performs read-only is re-implemented here 1:1 (ssh subprocess,
  plain HTTP/TCP) so the UI can show structured results instead of parsed
  text;
* the actual install reuses ``Install-SceneStudio.ps1`` in its unattended
  mode (``-Unattended -Answers <file>``) as a child process. Review, the
  bounded apps.yaml/secrets.yaml mutation, backups, the validated deployers
  (backup/stage/hash/verify/rollback), the optional card deploy, and the
  sanitized support report all remain the wizard's tested code paths — the
  UI only streams their output into a log console.
* the deployment answers are written to a temp file in the wizard's own
  answers schema (confirm_install included) — secrets are NEVER part of it.
  The HA long-lived token and the Hue application key are held in this
  process's memory only (entered in the browser or inherited from the
  environment) and passed to the child installer through environment
  variables, exactly like an interactive wizard session.

Cross-platform by construction: Python 3.9+ stdlib, any browser, ssh, and
pwsh 7 — the same four prerequisites the CLI wizard already requires. No
Windows-only APIs (no registry, no Start-Process, no shell=True; paths via
pathlib; the only OS-specific branch is wrapping ``.cmd`` shims with
cmd.exe on Windows for subprocess).

Security posture (this is a LOCAL single-user server):
* binds to the loopback interface only (default 127.0.0.1);
* every ``/api`` call must carry the one-time session token printed in the
  launch URL (a custom header, which also blocks cross-origin requests from
  other pages via preflight) and the Host header must match the bound
  address (DNS-rebinding guard);
* no CORS headers; static assets carry a restrictive CSP;
* secret values are never echoed by any endpoint, never logged, and are
  scrubbed from captured installer output (defense in depth — the wizard
  never prints them anyway).

Usage::

    python installer/ui/server.py [--port 8765] [--no-browser] [--host 127.0.0.1]
"""

