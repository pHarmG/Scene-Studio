def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--host", default="127.0.0.1", help="bind address (default: 127.0.0.1 — keep it local)")
    parser.add_argument("--port", type=int, default=8765, help="port (default: 8765; 0 picks a free port)")
    parser.add_argument("--no-browser", action="store_true", help="do not open the browser automatically")
    args = parser.parse_args(argv)

    try:
        session = InstallerSession()
    except UiError as exc:
        print(f"Scene Studio installer UI cannot start: {exc.message}", file=sys.stderr)
        return 1

    host = args.host
    if host not in ("127.0.0.1", "localhost", "::1"):
        print("warning: binding a non-loopback address exposes this installer to your network.", file=sys.stderr)

    try:
        server = InstallerUiServer((host, args.port), InstallerUiHandler, session)
    except OSError as exc:
        print(f"cannot bind {host}:{args.port}: {exc}", file=sys.stderr)
        return 1
    InstallerUiHandler.session = session
    port = server.server_address[1]
    url = f"http://{host}:{port}/?token={session.token}"
    # flush=True: the banner (and the token URL) must reach piped stdout
    # immediately — launchers and tests parse it line by line.
    print("Scene Studio Installer UI", flush=True)
    print(f"  bundle : {BUNDLE_ROOT} ({session.bundle_mode}, v{session.version})", flush=True)
    print(f"  open   : {url}", flush=True)
    print("  this window must stay open; press Ctrl+C to stop the installer UI.", flush=True)
    if not args.no_browser:
        threading.Timer(0.4, lambda: webbrowser.open(url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\ninstaller UI stopped.")
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
